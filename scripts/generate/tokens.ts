import { ACCENTS, DEFAULT_ACCENT, accentCss, accentProperties, deriveAccent } from '../../shared/accents.ts';

/**
 * The colors from the web's semantic tokens in app-web/src/index.css and the theme colors in shared/accents.ts: the web's
 * per-choice accent CSS, and on iOS `Palette` with one light and one dark value per fixed color token, each theme color's
 * derived pair, and the AccentColor asset, which system chrome uses before the app sets the window's tint.
 */

type Rgba = [number, number, number, number];
type Tokens = Record<string, string>;

function block(css: string, selector: string): Tokens {
	const start = css.indexOf(`\n${selector} {`);
	if (start < 0) throw new Error(`index.css has no ${selector} block`);
	const body = css.slice(start, css.indexOf('\n}', start));
	return Object.fromEntries(
		[...body.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [name!, value!.trim()]),
	);
}

function color(tokens: Tokens, value: string): Rgba | undefined {
	const reference = value.match(/^var\((--[\w-]+)\)$/);
	if (reference) {
		const target = tokens[reference[1]!];
		if (target === undefined) throw new Error(`Unknown token ${reference[1]}`);
		return color(tokens, target);
	}
	const hex = value.match(/^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i);
	if (hex) return [...hex.slice(1, 4).map(h => parseInt(h, 16)), 1] as Rgba;
	const rgb = value.match(/^rgb\((\d+) (\d+) (\d+)(?: \/ ([\d.]+))?\)$/);
	if (rgb) return [Number(rgb[1]), Number(rgb[2]), Number(rgb[3]), rgb[4] ? Number(rgb[4]) : 1];
	return undefined;
}

const swiftName = (token: string) =>
	token.replace(/^--(color-)?/, '').replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

const literal = ([r, g, b, a]: Rgba) => {
	const hex = `0x${[r, g, b].map(c => c.toString(16).padStart(2, '0').toUpperCase()).join('')}`;
	return a === 1 ? `SRGB(${hex})` : `SRGB(${hex}, ${a})`;
};

const colorset = (lightValue: Rgba, darkValue: Rgba) => {
	const entry = ([r, g, b, a]: Rgba) => ({
		'color-space': 'srgb',
		components: {
			alpha: a.toFixed(3),
			blue: `0x${b.toString(16).padStart(2, '0').toUpperCase()}`,
			green: `0x${g.toString(16).padStart(2, '0').toUpperCase()}`,
			red: `0x${r.toString(16).padStart(2, '0').toUpperCase()}`,
		},
	});
	const colors = [
		{ color: entry(lightValue), idiom: 'universal' },
		{ appearances: [{ appearance: 'luminosity', value: 'dark' }], color: entry(darkValue), idiom: 'universal' },
	];
	return `${JSON.stringify({ colors, info: { author: 'xcode', version: 1 } }, null, '\t')}\n`;
};

const ACCENT_NAMES = Object.keys(accentProperties(deriveAccent(ACCENTS[DEFAULT_ACCENT].base).light));
const usesAccent = (value: string) => ACCENT_NAMES.some(name => value === `var(${name})`);

const accentsCss = () =>
	`/* Generated by scripts/generate from shared/accents.ts. Do not edit. */\n${accentCss(ACCENTS[DEFAULT_ACCENT].base)}${Object.entries(
		ACCENTS,
	)
		.map(([key, { base }]) => accentCss(base, key))
		.join('')}`;

/** Only the names and base colors: the app derives each accent at runtime with `Core`'s port of `deriveAccent`. */
function accentsSwift() {
	const property = (name: string, value: (accent: { name: string; base: string }) => string) =>
		`    var ${name}: String {\n        switch self {\n${Object.entries(ACCENTS)
			.map(([key, accent]) => `        case .${key}: ${value(accent)}`)
			.join('\n')}\n        }\n    }`;
	return `/// Each theme color's name and base color.
extension API.AccentChoice {
${property('name', accent => JSON.stringify(accent.name))}

${property('base', accent => JSON.stringify(accent.base))}
}
`;
}

export function tokenFiles(css: string): Record<string, string> {
	const defaults = deriveAccent(ACCENTS[DEFAULT_ACCENT].base);
	const light = { ...block(css, '@theme'), ...block(css, ':root'), ...accentProperties(defaults.light) };
	const dark = { ...light, ...block(css, ":root[data-theme='dark']"), ...accentProperties(defaults.dark) };
	const names = Object.keys(light).filter(
		name => !ACCENT_NAMES.includes(name) && !usesAccent(light[name]!) && color(light, light[name]!),
	);
	const lines = names.map(name => {
		const pair = `light: ${literal(color(light, light[name]!)!)}, dark: ${literal(color(dark, dark[name]!)!)}`;
		return `    static let ${swiftName(name)} = Color(${pair})`;
	});
	const styles = names.map(name => `    static var ${swiftName(name)}: Color { Palette.${swiftName(name)} }`);
	const tokens = `// Generated by scripts/generate from app-web/src/index.css and shared/accents.ts. Do not edit.
import Core
import SwiftUI

/// The web's semantic color tokens, one light and one dark value each.
enum Palette {
${lines.join('\n')}
}

extension ShapeStyle where Self == Color {
${styles.join('\n')}
}

${accentsSwift()}`;
	const accent = colorset(color(light, 'var(--color-accent)')!, color(dark, 'var(--color-accent)')!);
	return {
		'app-web/src/lib/generated/accents.css': accentsCss(),
		'app-ios/Sources/App/Generated/Tokens.swift': tokens,
		'app-ios/Sources/App/Assets.xcassets/AccentColor.colorset/Contents.json': accent,
	};
}
