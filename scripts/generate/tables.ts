import { getTableColumns, getTableName } from 'drizzle-orm';
import { COLUMN_TYPES, type LocalKind } from './columns';
import type { SQLiteTable } from 'drizzle-orm/sqlite-core';
import { COLUMN_VALUES } from '../../shared/db/json';
import { SYNCED_TABLES } from '../../shared/db/schema';

/**
 * sync-engine stores only text, integer, and real, so JSON columns are JSON text and every client keeps the server's
 * column names.
 */

type Column = { name: string; columnType: string; notNull: boolean; primary: boolean; enumValues?: readonly string[] };
type SyncedColumn = { key: string; name: string; kind: LocalKind; notNull: boolean; enumValues?: readonly string[] };
export type SyncedTable = { name: string; columns: SyncedColumn[] };

const valuesOf = (table: string): Record<string, unknown> =>
	(COLUMN_VALUES as Record<string, Record<string, unknown>>)[table] ?? {};

export function syncedTables(): SyncedTable[] {
	return Object.values(SYNCED_TABLES).map(table => {
		const name = getTableName(table as SQLiteTable);
		const columns = Object.entries(getTableColumns(table as SQLiteTable) as Record<string, Column>).map(
			([key, column]) => {
				const kind = COLUMN_TYPES[column.columnType]?.local;
				if (!kind) throw new Error(`${name}.${key}: sync-engine has no type for ${column.columnType}`);
				return { key, name: column.name, kind, notNull: column.notNull, enumValues: column.enumValues };
			},
		);
		return { name, columns };
	});
}

const camel = (name: string) => name.replace(/_(\w)/g, (_, c: string) => c.toUpperCase());

export type SwiftModel = { name: string; properties: string[]; required: string[] };

/**
 * The iOS side of every synced table: each table's layout on the Core type that holds its rows, which `SyncedRow` in
 * the App target reads and writes through GRDB. The engine's DDL is `SyncSchema.swift`, which sync-engine writes. A key the Core type lacks (`userId`, and
 * `id` for settings) is the row's own. `required` says which keys the type decodes even when null; the rest are
 * dropped when null, like a missing `sourceKey`.
 */
export function swiftRowsModule(models: Record<string, SwiftModel>): string {
	const tables = syncedTables().map(table => {
		const model = models[camel(table.name)];
		if (!model) throw new Error(`${table.name}: no Swift model names it in x-table`);
		const missing = table.columns.filter(c => !['id', 'userId'].includes(c.key) && !model.properties.includes(c.key));
		if (missing.length) throw new Error(`${model.name} lacks ${table.name} columns ${missing.map(c => c.key)}`);
		return { table, model };
	});
	const layouts = tables.map(({ table, model }) => {
		const columns = table.columns.map(column => {
			const required = !model.properties.includes(column.key) || model.required.includes(column.key);
			return `\t\t.init(key: "${column.key}", name: "${column.name}", kind: .${column.kind}, required: ${required}),`;
		});
		return [
			`extension API.${model.name}: SyncedValue {`,
			`\tstatic let layout = RowLayout(table: "${table.name}", columns: [\n${columns.join('\n')}\n\t])`,
			'}',
		].join('\n');
	});
	const values = tables.map(({ table, model }) => `\t"${table.name}": API.${model.name}.self,`);
	return [
		'// Generated by scripts/generate from shared/db/schema.ts. Do not edit.',
		'import Core',
		'',
		layouts.join('\n\n'),
		'',
		'/// The Core type of each synced table, by table name.',
		`let syncedValues: [String: any SyncedValue.Type] = [\n${values.join('\n')}\n]`,
		'',
	]
		.join('\n')
		.replaceAll('\t', '    ');
}
