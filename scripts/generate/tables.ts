import { getTableColumns, getTableName } from 'drizzle-orm';
import type { PgTable } from 'drizzle-orm/pg-core';
import { COLUMN_VALUES } from '../../shared/db/json';
import { SYNCED_TABLES } from '../../shared/db/schema';

/**
 * PowerSync stores only text, integer, and real, so JSON columns become JSON text and every client keeps the
 * server's column names.
 */

type Column = { name: string; columnType: string; notNull: boolean; primary: boolean; enumValues?: readonly string[] };
type Kind = 'text' | 'integer' | 'real' | 'json';
type SyncedColumn = { key: string; name: string; kind: Kind; notNull: boolean; enumValues?: readonly string[] };
export type SyncedTable = { name: string; columns: SyncedColumn[] };

const KIND: Record<string, Kind> = {
	PgText: 'text',
	PgInteger: 'integer',
	PgBigInt53: 'integer',
	PgDoublePrecision: 'real',
	PgJsonb: 'json',
};

const valuesOf = (table: string): Record<string, unknown> =>
	(COLUMN_VALUES as Record<string, Record<string, unknown>>)[table] ?? {};

export function syncedTables(): SyncedTable[] {
	return Object.values(SYNCED_TABLES).map(table => {
		const name = getTableName(table as PgTable);
		const columns = Object.entries(getTableColumns(table as PgTable) as Record<string, Column>).map(([key, column]) => {
			const kind = KIND[column.columnType];
			if (!kind) throw new Error(`${name}.${key}: PowerSync has no type for ${column.columnType}`);
			return { key, name: column.name, kind, notNull: column.notNull, enumValues: column.enumValues };
		});
		return { name, columns };
	});
}

const camel = (name: string) => name.replace(/_(\w)/g, (_, c: string) => c.toUpperCase());

/**
 * A local-only table outside PowerSync's schema, so it never syncs, and triggers on the tables under PowerSync's views
 * that note every row any writer changes: this client, another tab, a sync, or a clear. Both clients read it to reload
 * only what changed. Creating it is setup, run once per database; a PowerSync release that renamed its tables fails
 * here, loudly, with "no such table".
 */
const CHANGE_LOG = 'procrastimate_changes';
const DATABASE_OWNER = 'procrastimate_owner';

export function changeLogStatements(): string[] {
	const events = [
		['insert', 'NEW'],
		['update', 'NEW'],
		['delete', 'OLD'],
	] as const;
	return [
		`CREATE TABLE IF NOT EXISTS ${CHANGE_LOG} (seq INTEGER PRIMARY KEY AUTOINCREMENT, tbl TEXT NOT NULL, id TEXT NOT NULL)`,
		...syncedTables().flatMap(({ name }) =>
			events.map(
				([event, row]) =>
					`CREATE TRIGGER IF NOT EXISTS ${CHANGE_LOG}_${name}_${event} AFTER ${event.toUpperCase()} ON ps_data__${name} BEGIN INSERT INTO ${CHANGE_LOG} (tbl, id) VALUES ('${name}', ${row}.id); END`,
			),
		),
	];
}

export function webTablesModule(): string {
	const tables = syncedTables().map(table => {
		const values = valuesOf(camel(table.name));
		const columns = table.columns.map(column => {
			let code =
				column.kind === 'json'
					? `text('${column.name}', { mode: 'json' })`
					: column.enumValues?.length
						? `text('${column.name}', { enum: ${JSON.stringify(column.enumValues)} })`
						: `${column.kind}('${column.name}')`;
			if (column.key in values) code += `.$type<ColumnValue<'${camel(table.name)}', '${column.key}'>>()`;
			if (column.key === 'id') code += '.primaryKey()';
			if (column.notNull) code += '.notNull()';
			return `\t${column.key}: ${code},`;
		});
		return `export const ${camel(table.name)} = sqliteTable('${table.name}', {\n${columns.join('\n')}\n});`;
	});
	const names = syncedTables().map(table => camel(table.name));
	return [
		'// Generated by scripts/generate from shared/db/schema.ts. Do not edit.',
		"import { DrizzleAppSchema } from '@powersync/drizzle-driver';",
		"import { integer, real, sqliteTable, text } from 'drizzle-orm/sqlite-core';",
		"import type { ColumnValue } from '../../../../shared/db/json.ts';",
		'',
		tables.join('\n\n'),
		'',
		`export const localTables = { ${names.join(', ')} };`,
		'export const AppSchema = new DrizzleAppSchema(localTables);',
		'',
		'/** Every row change any writer made, in order. Local only: it is not in `AppSchema`, so it never syncs. */',
		`export const changeLog = sqliteTable('${CHANGE_LOG}', {`,
		"\tseq: integer('seq').primaryKey({ autoIncrement: true }),",
		"\ttbl: text('tbl').notNull(),",
		"\tid: text('id').notNull(),",
		'});',
		'',
		'/** Whose rows the database holds. Local only, like `changeLog`. */',
		`export const databaseOwner = sqliteTable('${DATABASE_OWNER}', {`,
		"\towner: text('owner').primaryKey(),",
		'});',
		'',
		`export const SETUP_STATEMENTS = ${JSON.stringify(
			[...changeLogStatements(), `CREATE TABLE IF NOT EXISTS ${DATABASE_OWNER} (owner TEXT PRIMARY KEY)`],
			null,
			'\t',
		)};`,
		'',
	].join('\n');
}

export type SwiftModel = { name: string; properties: string[]; required: string[] };

const POWERSYNC_TYPE: Record<Kind, string> = { text: 'text', integer: 'integer', real: 'real', json: 'text' };

/**
 * The iOS side of every synced table: the PowerSync schema, and each table's layout on the Core type that holds its
 * rows, which `SyncedRow` in the App target reads and writes through GRDB. A key the Core type lacks (`userId`, and
 * `id` for settings) is the row's own. `required` says which keys the type decodes even when null; the rest are
 * dropped when null, like a missing `sourceKey`.
 */
export function swiftRowsModule(models: Record<string, SwiftModel>): string {
	const tables = syncedTables().map(table => {
		const model = models[camel(table.name)];
		if (!model) throw new Error(`${table.name}: no Swift model names it in x-table`);
		const missing = table.columns.filter(c => !['id', 'userId'].includes(c.key) && !model.properties.includes(c.key));
		if (missing.length) throw new Error(`${model.name} lacks ${table.name} columns ${missing.map(c => c.key)}`);
		return { table, model };
	});
	const schema = tables.map(({ table }) => {
		const columns = table.columns
			.filter(column => column.name !== 'id')
			.map(column => `\t\t.${POWERSYNC_TYPE[column.kind]}("${column.name}"),`);
		return `\tTable(name: "${table.name}", columns: [\n${columns.join('\n')}\n\t], ignoreEmptyUpdates: true)`;
	});
	const layouts = tables.map(({ table, model }) => {
		const columns = table.columns.map(column => {
			const required = !model.properties.includes(column.key) || model.required.includes(column.key);
			return `\t\t.init(key: "${column.key}", name: "${column.name}", kind: .${column.kind}, required: ${required}),`;
		});
		return [
			`extension API.${model.name}: SyncedValue {`,
			`\tstatic let layout = RowLayout(table: "${table.name}", columns: [\n${columns.join('\n')}\n\t])`,
			'}',
		].join('\n');
	});
	const values = tables.map(({ table, model }) => `\t"${table.name}": API.${model.name}.self,`);
	return [
		'// Generated by scripts/generate from shared/db/schema.ts. Do not edit.',
		'import Core',
		'import PowerSync',
		'',
		'/// The local database PowerSync keeps: every synced table under its server name. JSON columns hold JSON text.',
		`let syncSchema = Schema(\n${schema.join(',\n')}\n)`,
		'',
		layouts.join('\n\n'),
		'',
		'/// The Core type of each synced table, by table name.',
		`let syncedValues: [String: any SyncedValue.Type] = [\n${values.join('\n')}\n]`,
		'',
		'/// Every row change any writer made, in order. Local only: it is not in `syncSchema`, so it never syncs.',
		`let changeLogTable = "${CHANGE_LOG}"`,
		'',
		'/// Creates the change log and the triggers that fill it. Setup, run once per database.',
		`let changeLogStatements: [String] = [\n${changeLogStatements()
			.map(statement => `\t${JSON.stringify(statement)},`)
			.join('\n')}\n]`,
		'',
	]
		.join('\n')
		.replaceAll('\t', '    ');
}
